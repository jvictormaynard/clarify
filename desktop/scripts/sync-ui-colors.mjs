import { readFileSync, writeFileSync } from "node:fs";

const palette = JSON.parse(readFileSync(new URL("../../shared/ui-colors.json", import.meta.url), "utf8"));
const destination = new URL("../src/styles/shared-colors.css", import.meta.url);
for (const scheme of ["dark", "light"]) {
  if (Object.keys(palette[scheme]).sort().join() !== Object.keys(palette.dark).sort().join()) {
    throw new Error(`Shared color roles do not match: ${scheme}`);
  }
  for (const [role, value] of Object.entries(palette[scheme])) {
    if (!/^[a-z][a-zA-Z]+$/.test(role) || !/^#[\da-f]{6}$/i.test(value)) throw new Error(`Invalid shared color: ${scheme}.${role}`);
  }
}
const content = "/* Generated by desktop/scripts/sync-ui-colors.mjs. Do not edit. */\n:root {\n"
  + Object.entries(palette.dark).map(([role, value]) => {
    const name = role.replace(/[A-Z]/g, letter => `-${letter.toLowerCase()}`);
    return `  --shared-${name}: ${value};`;
  }).join("\n") + "\n}\n";

if (process.argv.includes("--check")) {
  if (readFileSync(destination, "utf8").replaceAll("\r\n", "\n") !== content) {
    throw new Error("Shared UI colors are out of sync. Run npm run colors:sync in desktop.");
  }
} else {
  writeFileSync(destination, content);
}
