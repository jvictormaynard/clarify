"""Generate client constants from the bounded processing wire contract."""

import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from shared.processing_contract import CONTRACT  # noqa: E402


def outputs():
    compact = json.dumps(CONTRACT, ensure_ascii=True, separators=(",", ":"))
    typescript = "// Generated by scripts/sync_processing_contract.py. Do not edit.\n"
    for name, key in (
        ("ContractOutputLanguage", "output_languages"),
        ("ContractOutputStyle", "writing_styles"),
    ):
        choices = " | ".join(json.dumps(value) for value in CONTRACT[key])
        typescript += f"export type {name} = {choices};\n"
    swift = (
        "// Generated by scripts/sync_processing_contract.py. Do not edit.\n"
        "import Foundation\n\n"
        "enum ProcessingContractData {\n"
        f'  private static let json = #"{compact}"#\n'
        "  static let value: [String: Any] = (try? JSONSerialization.jsonObject(with: Data(json.utf8))) as? [String: Any] ?? [:]\n"
        "}\n"
    )
    constants = "".join(
        f"  static let {destination}Text{direction.title()}Bytes = {limits['text_' + direction + '_bytes']}\n"
        for destination, limits in CONTRACT["limits"].items()
        for direction in ("input", "output")
    )
    swift = swift.rsplit("}\n", 1)[0] + constants + "}\n"
    cases = (ROOT / "shared/processing_outcome_cases.json").read_text(encoding="utf-8")
    swift_cases = (
        "// Generated by scripts/sync_processing_contract.py. Do not edit.\n"
        "import Foundation\n\n"
        "enum ProcessingOutcomeCases {\n"
        '  static let json = #"""\n' + cases + '"""#\n'
        "}\n"
    )
    return {
        ROOT / "shared/processing-contract.ts": typescript,
        ROOT / "mobile/modules/clarify-core/ios/ProcessingContractData.swift": swift,
        ROOT
        / "mobile/modules/clarify-core/tests/ProcessingOutcomeCases.swift": swift_cases,
    }


def main():
    for path, content in outputs().items():
        if "--check" in sys.argv:
            if not path.is_file() or path.read_text(encoding="utf-8") != content:
                raise SystemExit(
                    f"Processing contract is out of sync: {path.relative_to(ROOT)}"
                )
        else:
            path.write_text(content, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
