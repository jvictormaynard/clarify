"""Generate the native catalog from the single reviewed UI catalog."""

import argparse
import json
import os
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "mobile/modules/clarify-core/ios/Localization.swift"
CATALOG_PATH = "shared/ui_strings.json"
DESKTOP_KEYS_PATH = "shared/desktop_ui_keys.json"


def native_catalog(catalog, desktop_keys):
    """Unclassified text remains native; only reviewed desktop keys are excluded."""
    if not isinstance(catalog, dict):
        raise ValueError("The UI catalog must be an object")
    for source, entry in catalog.items():
        if (
            not isinstance(source, str)
            or not source
            or not isinstance(entry, dict)
            or set(entry) != {"pt", "en", "es"}
            or not all(isinstance(value, str) and value for value in entry.values())
        ):
            raise ValueError(f"Incomplete translation: {source}")
    if (
        not isinstance(desktop_keys, list)
        or not all(isinstance(key, str) and key in catalog for key in desktop_keys)
        or len(desktop_keys) != len(set(desktop_keys))
    ):
        raise ValueError("Desktop UI scope must contain unique, existing catalog keys")
    return {key: value for key, value in catalog.items() if key not in desktop_keys}


def check_desktop_scope(desktop_keys):
    # Native and React Native callers must opt a key back into the shared scope.
    for directory in ("native", "modules", "src", "plugins", "scripts"):
        for folder, directories, names in os.walk(ROOT / "mobile" / directory):
            directories[:] = [
                name for name in directories if name not in {"node_modules", ".build"}
            ]
            for name in names:
                path = Path(folder) / name
                if name == "Localization.swift" or path.suffix not in {
                    ".swift",
                    ".m",
                    ".mm",
                    ".h",
                    ".ts",
                    ".tsx",
                    ".js",
                    ".jsx",
                    ".cjs",
                }:
                    continue
                source = path.read_text(encoding="utf-8")
                for key in desktop_keys:
                    if key in source:
                        raise ValueError(
                            f"Desktop UI key is used by mobile: {key} ({path})"
                        )


def generated():
    catalog = json.loads((ROOT / CATALOG_PATH).read_text(encoding="utf-8"))
    desktop_keys = json.loads((ROOT / DESKTOP_KEYS_PATH).read_text(encoding="utf-8"))
    projected = native_catalog(catalog, desktop_keys)
    check_desktop_scope(desktop_keys)
    payload = json.dumps(projected, ensure_ascii=False, separators=(",", ":"))
    return (
        '''// Generated by scripts/sync_locales.py. Edit shared/ui_strings.json.
import Foundation

enum ClarifyLocale {
  static func normalize(_ value: String) -> String {
    let primary = value.lowercased().replacingOccurrences(of: "_", with: "-").split(separator: "-").first.map(String.init) ?? "en"
    return ["pt", "es"].contains(primary) ? primary : "en"
  }
  static var language: String { normalize(Locale.preferredLanguages.first ?? "en") }
  static let messages: [String: [String: String]] = {
    let json = #"""
'''
        + payload
        + '''
"""#
    return (try? JSONSerialization.jsonObject(with: Data(json.utf8))) as? [String: [String: String]] ?? [:]
  }()
}
func L(_ source: String, _ values: [String: String] = [:], language: String = ClarifyLocale.language) -> String {
  var text = ClarifyLocale.messages[source]?[ClarifyLocale.normalize(language)] ?? source
  for (key, value) in values { text = text.replacingOccurrences(of: "{" + key + "}", with: value) }
  return text
}
'''
    )


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    result = generated()
    if args.check:
        if not TARGET.exists() or TARGET.read_text(encoding="utf-8") != result:
            raise SystemExit(
                "Native translations are stale. Run python scripts/sync_locales.py."
            )
    else:
        TARGET.write_text(result, encoding="utf-8")
