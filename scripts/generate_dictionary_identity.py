"""Generate frontend casefold data from the desktop's Python Unicode database."""

import argparse
import json
from pathlib import Path
import sys
import unicodedata

TARGET = (
    Path(__file__).resolve().parents[1] / "desktop/src/settings/dictionary-identity.ts"
)


def generated():
    mappings = [
        (code, chr(code).casefold())
        for code in range(sys.maxunicode + 1)
        if chr(code).casefold() != chr(code)
    ]
    simple = [
        (code, ord(folded) - code) for code, folded in mappings if len(folded) == 1
    ]
    ranges, index = [], 0
    while index < len(simple):
        start, delta = simple[index]
        end, step = start, 1
        if (
            index + 1 < len(simple)
            and simple[index + 1][1] == delta
            and simple[index + 1][0] - start in (1, 2)
        ):
            step = simple[index + 1][0] - start
            while (
                index + 1 < len(simple)
                and simple[index + 1][1] == delta
                and simple[index + 1][0] - end == step
            ):
                index += 1
                end = simple[index][0]
        ranges.append([start, end, step, delta])
        index += 1
    expansions = [[code, folded] for code, folded in mappings if len(folded) > 1]
    spaces = [code for code in range(sys.maxunicode + 1) if chr(code).isspace()]

    def rows(values):
        return "\n".join(
            "  " + json.dumps(value, ensure_ascii=True) + "," for value in values
        )

    return f"""// Generated by scripts/generate_dictionary_identity.py. Do not edit the data.
// Python {sys.version_info.major}.{sys.version_info.minor}; unicodedata {unicodedata.unidata_version}.
// Strip/NFC/casefold identity follows the existing Python dictionary contract.
const ranges: ReadonlyArray<readonly [number, number, number, number]> = [
{rows(ranges)}
];
const expansions = new Map<number, string>([
{rows(expansions)}
]);
const spaces = new Set<number>({json.dumps(spaces)});

export function unicodeCasefold(value: string): string {{
  let result = "";
  for (const scalar of value) {{
    const code = scalar.codePointAt(0)!;
    const expansion = expansions.get(code);
    if (expansion !== undefined) {{ result += expansion; continue; }}
    let low = 0, high = ranges.length - 1, folded = scalar;
    while (low <= high) {{
      const middle = (low + high) >>> 1;
      const [start, end, step, delta] = ranges[middle];
      if (code < start) high = middle - 1;
      else if (code > end) low = middle + 1;
      else {{ if ((code - start) % step === 0) folded = String.fromCodePoint(code + delta); break; }}
    }}
    result += folded;
  }}
  return result;
}}

export function dictionaryIdentity(value: string): string {{
  const scalars = Array.from(value);
  let start = 0, end = scalars.length;
  while (start < end && spaces.has(scalars[start].codePointAt(0)!)) start++;
  while (end > start && spaces.has(scalars[end - 1].codePointAt(0)!)) end--;
  return unicodeCasefold(scalars.slice(start, end).join("").normalize("NFC"));
}}
"""


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    result = generated()
    if args.check:
        if TARGET.read_text("utf-8") != result:
            raise SystemExit(
                "Dictionary identity data is stale. Regenerate with the pinned Python runtime."
            )
    else:
        TARGET.write_text(result, encoding="utf-8")
